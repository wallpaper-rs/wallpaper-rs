const M1: [[f64; 3]; 3] = [
    [0.4122214708, 0.5363325363, 0.0514459929],
    [0.2119034982, 0.6806995451, 0.1073969566],
    [0.0883024619, 0.2817188376, 0.6299787005],
];
const M2: [[f64; 3]; 3] = [
    [0.2104542553, 0.7936177850, -0.0040720468],
    [1.9779984951, -2.4285922050, 0.4505937099],
    [0.0259040371, 0.7827717662, -0.8086757660],
];
const M1_INV: [[f64; 3]; 3] = [
    [4.076741661347994, -3.3077115904081933, 0.23096992872942795],
    [-1.2684380040921763, 2.6097574006633715, -0.3413193963102196],
    [-0.004196086541837074, -0.7034186144594495, 1.7076147009309446],
];
const M2_INV: [[f64; 3]; 3] = [
    [0.9999999984505197, 0.3963377921737678, 0.21580375806075883],
    [1.0000000088817607, -0.10556134232365633, -0.0638541747717059],
    [1.0000000546724106, -0.08948418209496574, -1.2914855378640917],
];

fn mul(m: &[[f64; 3]; 3], v: [f64; 3]) -> [f64; 3] {
    [0, 1, 2].map(|i| m[i][0] * v[0] + m[i][1] * v[1] + m[i][2] * v[2])
}

pub(crate) fn linear(byte: u8) -> f64 {
    let c = f64::from(byte) / 255.0;
    if c <= 0.04045 { c / 12.92 } else { ((c + 0.055) / 1.055).powf(2.4) }
}

fn gamma(c: f64) -> f64 {
    let c = c.clamp(0.0, 1.0);
    if c <= 0.0031308 { c * 12.92 } else { 1.055 * c.powf(1.0 / 2.4) - 0.055 }
}

pub(crate) fn lab(rgb: [u8; 3]) -> [f64; 3] {
    let l = mul(&M1, rgb.map(linear)).map(f64::cbrt);
    mul(&M2, l)
}

pub(crate) fn rgb(l: f64, chroma: f64, hue: f64) -> [u8; 3] {
    let mut chroma = chroma;
    let mut out = [0.0; 3];
    for _ in 0..60 {
        let cone = mul(&M2_INV, [l, chroma * hue.cos(), chroma * hue.sin()]).map(|v| v * v * v);
        out = mul(&M1_INV, cone);
        let min = out.iter().copied().fold(f64::INFINITY, f64::min);
        let max = out.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        if min >= -1e-4 && max <= 1.0 + 1e-4 {
            break;
        }
        chroma *= 0.95;
    }
    out.map(|v| (gamma(v) * 255.0).round_ties_even() as u8)
}
